-- 1. TIPOS ENUM PERSONALIZADOS
DO $$ BEGIN
    CREATE TYPE status_aluno AS ENUM ('pendente', 'aprovado', 'recusado', 'banido', 'admin');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
    CREATE TYPE tipo_movimentacao AS ENUM ('entrada', 'saida');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

-- 2. TABELA: administradores
CREATE TABLE IF NOT EXISTS public.administradores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    escola VARCHAR(150) NOT NULL,
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 3. TABELA: alunos
CREATE TABLE IF NOT EXISTS public.alunos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    escola VARCHAR(150) NOT NULL,
    turma VARCHAR(50) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    status status_aluno NOT NULL DEFAULT 'pendente'::status_aluno,
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 4. TABELA: produtos
CREATE TABLE IF NOT EXISTS public.produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    categoria VARCHAR(50) NOT NULL,
    preco NUMERIC(10,2) NOT NULL,
    imagem VARCHAR(500),
    estoque INTEGER NOT NULL DEFAULT 0
);

-- 5. TABELA: pedidos
CREATE TABLE IF NOT EXISTS public.pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    senha INTEGER NOT NULL,
    itens JSONB NOT NULL DEFAULT '[]'::jsonb,
    total NUMERIC(10,2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Pendente',
    data_hora TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 6. TABELA: movimentacoes_estoque (Giro de Estoque)
CREATE TABLE IF NOT EXISTS public.movimentacoes_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT REFERENCES public.produtos(id) ON DELETE SET NULL,
    produto_nome VARCHAR(150) NOT NULL,
    tipo tipo_movimentacao NOT NULL,
    quantidade INTEGER NOT NULL,
    motivo VARCHAR(255),
    saldo_apos INTEGER NOT NULL DEFAULT 0,
    data_hora TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

